# 규칙 원천 = 에디터 지침 [한국어 결] 동축(im-not-ai 분류 체계 v2.0 · MIT · 문장 축 발췌 개작).
# 개정 시 = 이 파일 한 곳 + 각 레인 PVER 도장(캐시 강제 재생성) 동반.

TONE_BLOCK='[한국어 결 — AI 번역투 소거(공용)]
문장의 결만 다듬는 규칙이다 — 위·아래의 레인 고유 말투 지시(톤·인사·형식)가 항상 우선이고, 아래 무늬만 피한다:
- 이중 피동·"~에 의해" 피동 금지: "발생되어진다"→"발생한다" · "알고리즘에 의해 밀린"→"알고리즘이 밀어낸".
- "~에 대해/~에 있어/~와 관련하여/~를 통해" 남발 금지 → 조사로 직결("규제에 대해 논의"→"규제를 논의").
- "~할 수 있다" 남발 금지 — 확정 사실은 단언, 진짜 전망·미확정만 완곡.
- 이중 완곡 금지("~할 가능성이 있을 수 있다"→"~할 수 있다").
- 영어식 대명사 반복 금지("그는 ~. 그는 ~" 연쇄 → 생략하거나 자연 연결).
- AI 관용구 금지: "결론적으로"·"시사하는 바가 크다"·"주목할 만하다"·"~할 때입니다".
- 형식명사 연속 금지("~라는 점에 있다"·"~다는 것이다" 연발 → 직결 종결).
- 같은 종결어미 3연속·"A가 아니라 B다" 문형 연쇄 금지 — 길이·어미를 변주.
규칙 밖 단순 동의어 교체는 하지 마라 — 고칠 무늬가 없으면 원래 문장이 정답이다.'
