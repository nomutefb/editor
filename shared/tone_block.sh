#   드리프트) 이 한 벌을 넷이 ${TONE_BLOCK} 로 참조한다.
# 계약: **문장의 결만** — 각 레인의 고유 말투 지시(친근 소식통 톤·인사 문법·이모지·형식·팬픽 변주)가
